#!/usr/bin/env python3
"""Sponsor logos for the reel: assets/sponsors/*.svg -> c/src/logos.h and src/logos.rs.

  python3 tools/sim/logo.py [--preview=out.png]

The LOGOS table below says how to cut each picture: how many grid rows it
gets (the grid is 16 rows high), an optional crop (fractions of the
picture) and which pixels count as ink. SVGs are drawn with Inkscape;
PNGs work too (ink = alpha).

Each logo becomes greyscale: a pixel's brightness is how much of it the
picture covers, in 2 bits (off, 1/3, 2/3, full; the LED driver applies
gamma). Lone pixels with no lit neighbour are dropped. The result is
stored by column, one u32 each: bits 2r..2r+1 are row r, rows already
centred in the 16. A logo up to 17 columns wide stands still in the
middle; a wider one scrolls by like text (sponsors.c / sponsors.rs).

--preview draws the logos as the grid would show them.
"""
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets" / "sponsors"
ROWS = 16      # grid height
LEVELS = 3     # 2 bits
FLOOR = 0.15   # less coverage than this is off

# name, file, rows, crop (x0, y0, x1, y1 as fractions), ink, floor
LOGOS = [
    ("BADGETEAM", "badgeteam.svg", 11, None, "white", FLOOR),  # white brush letters (the SVG has black outlines)
    # the word only: the dish is mush at 16 pixels, and a high floor drops its thin lines behind the A
    ("ALLNET", "allnet.svg", 9, (0.33, 0.25, 1.0, 0.53), "alpha", 0.45),
    ("NICOLAI", "nicolai.svg", 16, None, "alpha", FLOOR),  # icon, "Nicolai" and (faint) "Electronics"
]


def load(path):
    if path.suffix == ".svg":
        with tempfile.TemporaryDirectory() as d:
            png = Path(d) / "logo.png"
            subprocess.run(["inkscape", str(path), "--export-type=png", f"--export-filename={png}",
                            "--export-width=1600"], check=True, capture_output=True)
            return Image.open(png).convert("RGBA")
    return Image.open(path).convert("RGBA")


def levels(img, rows, crop, ink, floor):
    w, h = img.size
    if crop:
        img = img.crop((round(crop[0] * w), round(crop[1] * h), round(crop[2] * w), round(crop[3] * h)))
    a = np.asarray(img).astype(float) / 255
    cover = a[..., 3]
    if ink == "white":
        cover = cover * (a[..., :3].mean(2) > 0.5)
    ys, xs = np.nonzero(cover > 0.5)
    cover = cover[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    cols = max(1, round(cover.shape[1] * rows / cover.shape[0]))
    small = np.asarray(Image.fromarray((cover * 255).astype(np.uint8)).resize((cols, rows), Image.BOX)) / 255
    q = np.round(small * LEVELS).astype(int)
    q[small < floor] = 0
    lit = q > 0
    pad = np.pad(lit, 1)
    neighbours = sum(np.roll(np.roll(pad, dy, 0), dx, 1) for dy in (-1, 0, 1) for dx in (-1, 0, 1)
                     if dy or dx)[1:-1, 1:-1]
    q[lit & (neighbours == 0)] = 0
    full = np.zeros((ROWS, cols), int)
    top = (ROWS - rows) // 2
    full[top:top + rows] = q
    return full


def words(q):
    return [sum(int(q[r, c]) << (2 * r) for r in range(ROWS)) for c in range(q.shape[1])]


def write(logos):
    c = ["/* Generated by tools/sim/logo.py from assets/sponsors; do not edit. */",
         "/* One u32 per column: bits 2r..2r+1 are row r's brightness, 0..3. */",
         "#pragma once", "#include <stdint.h>", ""]
    rs = ["//! Generated by tools/sim/logo.py from assets/sponsors; do not edit.",
          "//! One u32 per column: bits 2r..2r+1 are row r's brightness, 0..3.", ""]
    for name, q in logos:
        ws = words(q)
        body = ",\n    ".join(", ".join(f"0x{w:08X}" for w in ws[i:i + 6]) for i in range(0, len(ws), 6))
        c.append(f"static const uint32_t LOGO_{name}[{len(ws)}] = {{\n    {body},\n}};")
        rs.append(f"pub const {name}: [u32; {len(ws)}] = [\n    {body},\n];")
    (ROOT / "c" / "src" / "logos.h").write_text("\n".join(c) + "\n")
    (ROOT / "src" / "logos.rs").write_text("\n".join(rs) + "\n")


def preview(logos, out):
    k = 10
    width = max(q.shape[1] for _, q in logos) * k
    img = Image.new("RGB", (width, len(logos) * (ROWS * k + 8)), (15, 15, 18))
    d = ImageDraw.Draw(img)
    for i, (_, q) in enumerate(logos):
        y0 = i * (ROWS * k + 8)
        for r in range(ROWS):
            for col in range(q.shape[1]):
                v = q[r, col] * 85
                if v:
                    d.ellipse((col * k + 1, y0 + r * k + 1, col * k + k - 1, y0 + r * k + k - 1),
                              fill=(v, v * 15 // 16, v * 4 // 5))
    img.save(out)


def main(args):
    opts = dict(a[2:].split("=", 1) for a in args if a.startswith("--") and "=" in a)
    logos = []
    for name, file, rows, crop, ink, floor in LOGOS:
        q = levels(load(ASSETS / file), rows, crop, ink, floor)
        logos.append((name, q))
        print(f"{name}: {q.shape[1]} columns, {4 * q.shape[1]} bytes", file=sys.stderr)
    write(logos)
    if "preview" in opts:
        preview(logos, opts["preview"])


if __name__ == "__main__":
    main(sys.argv[1:])
