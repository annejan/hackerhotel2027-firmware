static inline const uint8_t *font_glyph(char c)
{
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    return GLYPHS[c >= ' ' && c <= 'Z' ? c - ' ' : 0];
}

/* width in columns of s, with one blank column between glyphs */
static inline int text_width(const char *s)
{
    size_t n = 0;
    while (s[n])
        n++;
    return n ? (int)n * (FONT_W + 1) - 1 : 0;
}

/* 3x5 digits for scores: five rows, bit 2 = left column */
static inline const uint8_t *font_digit3x5(uint8_t d)
{
    static const uint8_t D[10][5] = {
        {7, 5, 5, 5, 7}, {2, 6, 2, 2, 7}, {7, 1, 7, 4, 7}, {7, 1, 7, 1, 7}, {5, 5, 7, 1, 1},
        {7, 4, 7, 1, 7}, {7, 4, 7, 5, 7}, {7, 1, 2, 2, 2}, {7, 5, 7, 5, 7}, {7, 5, 7, 1, 7},
    };
    return D[d % 10];
}
